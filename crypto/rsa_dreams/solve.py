import math
from Crypto.Util.number import long_to_bytes

c = 5074616349947930347771128443869249667723941019037011379843932659330729580197593522845748676276068149443504037403162962894625104017380398816152166168830833
n = 6452268004013779272669102227661703532150635430524568657091997086066784917218113937677647594597481724133073200003104968955173212323278046973034541033497147
e = 65537
prime_sum = 161697499284577475400347684012866511237569864647822807778480533925514941939388

# We know that p, q are factors of x^2 - (p+q)*x + n = 0
# since this factors as (x - p)*(x - q) = 0
# We use the quadratic formula to recover p and q:

p = (prime_sum + math.isqrt(prime_sum**2 - 4*n)) // 2
q = (prime_sum - math.isqrt(prime_sum**2 - 4*n)) // 2
assert (p*q == n)

# Now decrypt
d = pow(e, -1, (p-1)*(q-1))
m = pow(c, d, n)
print(long_to_bytes(m))
